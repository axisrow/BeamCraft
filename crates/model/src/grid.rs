//! Project grid records and the bounded regular-family expression parser (T01.1).

use crate::command::CommandError;
use crate::error::ErrorCode;
use crate::id::ElementId;
use std::collections::BTreeSet;

/// The maximum number of grid elements in one project.
pub const MAX_GRIDS: usize = 64;
/// The maximum number of lines in either family.
pub const MAX_GRID_LINES_PER_FAMILY: usize = 200;
/// The minimum distance between consecutive regular lines, in millimetres.
pub const MIN_GRID_SPACING_MM: f64 = 1.0;
/// The maximum absolute regular-grid coordinate, in millimetres.
pub const GRID_COORDINATE_CAP_MM: f64 = 1_000_000.0;

/// A regular family's expression and its generated positions, in grid-local millimetres.
#[derive(Debug, Clone, PartialEq)]
pub struct RegularGridFamily {
    /// The normalized source expression; this remains authoritative for the positions.
    pub expression: String,
    /// Explicit line labels in position order.
    pub labels: Vec<String>,
    /// Stable line identities corresponding to `labels`.
    pub axis_ids: Vec<ElementId>,
    /// Start and end of each line along its direction.
    pub span_mm: [f64; 2],
    /// Generated coordinate positions.
    pub positions_mm: Vec<f64>,
}

/// A single user-drawn line, stored in grid-local XY coordinates.
#[derive(Debug, Clone, PartialEq)]
pub struct DrawnGridLine {
    /// Stable line identity.
    pub axis_id: ElementId,
    /// Unique within the grid, across both families.
    pub label: String,
    /// First endpoint `(x, y)` in millimetres.
    pub start_mm: [f64; 2],
    /// Second endpoint `(x, y)` in millimetres.
    pub end_mm: [f64; 2],
}

/// A regular or drawn grid family. Its mode is fixed when the grid is created.
#[derive(Debug, Clone, PartialEq)]
pub enum GridFamily {
    /// Parallel lines generated by one coordinate expression.
    Regular(RegularGridFamily),
    /// Independently authored straight segments.
    Drawn(Vec<DrawnGridLine>),
}

/// A project grid containing ordered U and V families of straight lines.
#[derive(Debug, Clone, PartialEq)]
pub struct Grid {
    /// Stable element identity.
    pub id: ElementId,
    /// Grid name; names are allowed to repeat.
    pub name: String,
    /// World translation in millimetres. Z must be zero.
    pub translation_mm: [f64; 2],
    /// Quaternion Z and W components of a Z-only rigid rotation. Kept exactly as authored.
    pub orientation_zw: [f64; 2],
    /// U-family lines.
    pub u: GridFamily,
    /// V-family lines.
    pub v: GridFamily,
}

/// Parse and normalize a regular-family coordinate expression.
///
/// The first number is the first position; later numbers are positive spacings. `N*D` expands
/// to N equal spacings. Input and output are bounded by the T01.1 limits.
pub fn parse_grid_expression(expression: &str) -> Result<(String, Vec<f64>), GridExpressionError> {
    if expression.len() > 4096 {
        return Err(GridExpressionError::Limit);
    }
    if expression.is_empty() {
        return Err(GridExpressionError::Invalid);
    }
    let words: Vec<&str> = expression
        .split(|c: char| c.is_ascii_whitespace() || c == ',')
        .filter(|word| !word.is_empty())
        .collect();
    if words.is_empty() || words.len() > MAX_GRID_LINES_PER_FAMILY {
        return Err(if words.len() > MAX_GRID_LINES_PER_FAMILY {
            GridExpressionError::Limit
        } else {
            GridExpressionError::Invalid
        });
    }
    let first = parse_coordinate(words.first().copied().ok_or(GridExpressionError::Invalid)?)?;
    let mut positions = Vec::with_capacity(MAX_GRID_LINES_PER_FAMILY.min(words.len()));
    positions.push(first);
    let normalized = words.join(" ");
    for word in words.iter().skip(1) {
        let (repeat, spacing_text) = if let Some((count, spacing)) = word.split_once('*') {
            if spacing.contains('*') || count.is_empty() || spacing.is_empty() {
                return Err(GridExpressionError::Invalid);
            }
            let count = count
                .parse::<usize>()
                .map_err(|_| GridExpressionError::Invalid)?;
            if count == 0 {
                return Err(GridExpressionError::Invalid);
            }
            if count > MAX_GRID_LINES_PER_FAMILY {
                return Err(GridExpressionError::Limit);
            }
            (count, spacing)
        } else {
            (1, *word)
        };
        let spacing = parse_coordinate(spacing_text)?;
        if spacing < MIN_GRID_SPACING_MM {
            return Err(GridExpressionError::Spacing);
        }
        let next_len = positions
            .len()
            .checked_add(repeat)
            .ok_or(GridExpressionError::Limit)?;
        if next_len > MAX_GRID_LINES_PER_FAMILY {
            return Err(GridExpressionError::Limit);
        }
        for _ in 0..repeat {
            let previous = positions
                .last()
                .copied()
                .ok_or(GridExpressionError::Invalid)?;
            let next = previous + spacing;
            if !next.is_finite() || next.abs() > GRID_COORDINATE_CAP_MM {
                return Err(GridExpressionError::Limit);
            }
            positions.push(next);
        }
    }
    Ok((normalized, positions))
}

impl Grid {
    /// Validate one complete grid before authoring or accepting stored records (T01-V01).
    /// Project-wide identity uniqueness and the project grid count are engine decisions.
    pub fn validate(&self) -> Result<(), CommandError> {
        let reject = |code, field, message| CommandError::new(code, field, message);
        if !crate::command::label_is_valid(&self.name) {
            return Err(reject(
                ErrorCode::InvalidArgument,
                "name",
                "invalid grid name",
            ));
        }
        if self.orientation_zw.iter().any(|n| !n.is_finite())
            || self.translation_mm.iter().any(|n| !n.is_finite())
        {
            return Err(reject(
                ErrorCode::NonFiniteNumber,
                "grid.frame",
                "grid frame is not finite",
            ));
        }
        if self
            .translation_mm
            .iter()
            .any(|n| n.abs() > 1_000_000_000.0)
        {
            return Err(reject(
                ErrorCode::LimitExceeded,
                "grid.frame",
                "grid origin exceeds the coordinate cap",
            ));
        }
        let [z, w] = self.orientation_zw;
        if z.abs() > 1.0 || w.abs() > 1.0 || ((z * z + w * w) - 1.0).abs() > 1e-6 {
            return Err(reject(
                ErrorCode::InvalidArgument,
                "grid.orientation",
                "invalid grid rotation quaternion",
            ));
        }
        let mut ids = BTreeSet::new();
        let mut labels = Vec::new();
        for family in [&self.u, &self.v] {
            match family {
                GridFamily::Regular(f) => {
                    let n = f.axis_ids.len();
                    if n > MAX_GRID_LINES_PER_FAMILY
                        || f.labels.len() > MAX_GRID_LINES_PER_FAMILY
                        || f.positions_mm.len() > MAX_GRID_LINES_PER_FAMILY
                    {
                        return Err(reject(
                            ErrorCode::LimitExceeded,
                            "grid.family",
                            "grid family exceeds the line cap",
                        ));
                    }
                    if n != f.labels.len() || n != f.positions_mm.len() {
                        return Err(reject(
                            ErrorCode::InvalidArgument,
                            "grid.family",
                            "grid family arrays disagree",
                        ));
                    }
                    let (_, positions) = parse_grid_expression(&f.expression).map_err(|e| {
                        reject(
                            match e {
                                GridExpressionError::Limit => ErrorCode::LimitExceeded,
                                GridExpressionError::NonFinite => ErrorCode::NonFiniteNumber,
                                _ => ErrorCode::InvalidArgument,
                            },
                            "grid.expression",
                            "invalid grid expression",
                        )
                    })?;
                    if positions != f.positions_mm {
                        return Err(reject(
                            ErrorCode::InvalidArgument,
                            "grid.expression",
                            "grid positions disagree with the expression",
                        ));
                    }
                    if f.span_mm.iter().any(|n| !n.is_finite()) {
                        return Err(reject(
                            ErrorCode::NonFiniteNumber,
                            "grid.span",
                            "grid span is not finite",
                        ));
                    }
                    if f.span_mm.iter().any(|n| n.abs() > GRID_COORDINATE_CAP_MM) {
                        return Err(reject(
                            ErrorCode::LimitExceeded,
                            "grid.span",
                            "grid span exceeds the coordinate cap",
                        ));
                    }
                    let [start, end] = f.span_mm;
                    if end - start < MIN_GRID_SPACING_MM {
                        return Err(reject(
                            ErrorCode::InvalidArgument,
                            "grid.span",
                            "GRID_LINE_DEGENERATE",
                        ));
                    }
                    for (id, label) in f.axis_ids.iter().zip(&f.labels) {
                        if !ids.insert(*id) {
                            return Err(reject(
                                ErrorCode::DuplicateId,
                                "grid.axis_ids",
                                "grid axis identity is repeated",
                            ));
                        }
                        labels.push(label.clone());
                    }
                }
                GridFamily::Drawn(lines) => {
                    if lines.len() > MAX_GRID_LINES_PER_FAMILY {
                        return Err(reject(
                            ErrorCode::LimitExceeded,
                            "grid.family",
                            "grid family exceeds the line cap",
                        ));
                    }
                    for line in lines {
                        if !ids.insert(line.axis_id) {
                            return Err(reject(
                                ErrorCode::DuplicateId,
                                "grid.axis_ids",
                                "grid axis identity is repeated",
                            ));
                        }
                        if line
                            .start_mm
                            .iter()
                            .chain(&line.end_mm)
                            .any(|n| !n.is_finite())
                        {
                            return Err(reject(
                                ErrorCode::NonFiniteNumber,
                                "grid.points",
                                "grid point is not finite",
                            ));
                        }
                        if line
                            .start_mm
                            .iter()
                            .chain(&line.end_mm)
                            .any(|n| n.abs() > GRID_COORDINATE_CAP_MM)
                        {
                            return Err(reject(
                                ErrorCode::LimitExceeded,
                                "grid.points",
                                "grid point exceeds the coordinate cap",
                            ));
                        }
                        let [ax, ay] = line.start_mm;
                        let [bx, by] = line.end_mm;
                        if (bx - ax).hypot(by - ay) < MIN_GRID_SPACING_MM {
                            return Err(reject(
                                ErrorCode::InvalidArgument,
                                "grid.points",
                                "GRID_LINE_DEGENERATE",
                            ));
                        }
                        labels.push(line.label.clone());
                    }
                }
            }
        }
        if labels.is_empty() {
            return Err(reject(
                ErrorCode::InvalidArgument,
                "grid.family",
                "grid has no lines",
            ));
        }
        validate_grid_labels(&labels).map_err(|e| {
            reject(
                ErrorCode::InvalidArgument,
                "grid.labels",
                match e {
                    GridLabelError::Duplicate => "GRID_LABEL_DUPLICATE",
                    GridLabelError::Count => "GRID_LABEL_COUNT",
                    _ => "GRID_LABEL_INVALID",
                },
            )
        })
    }

    /// The line identities, in U then V order.
    pub fn axis_ids(&self) -> impl Iterator<Item = ElementId> + '_ {
        [&self.u, &self.v].into_iter().flat_map(|family| {
            let (regular, drawn): (&[ElementId], &[DrawnGridLine]) = match family {
                GridFamily::Regular(f) => (&f.axis_ids, &[]),
                GridFamily::Drawn(lines) => (&[], lines),
            };
            regular
                .iter()
                .copied()
                .chain(drawn.iter().map(|line| line.axis_id))
        })
    }
}

/// A safe failure class for a malformed or over-limit regular expression.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GridExpressionError {
    /// Invalid number, spacing, or expression syntax.
    Invalid,
    /// A count or generated coordinate exceeds the contract cap.
    Limit,
    /// A parsed number is NaN or infinite.
    NonFinite,
    /// A spacing is smaller than one millimetre.
    Spacing,
}

/// The family order used by automatic grid-label generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GridLabelOrder {
    /// The first label belongs to the lowest coordinate.
    Ascending,
    /// The first label belongs to the highest coordinate.
    Descending,
}

/// A safe failure class for explicit labels or an automatic label scheme.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GridLabelError {
    /// Invalid characters, count, duplicate, or helper parameters.
    Invalid,
    /// The generated list or a label exceeds a contract cap.
    Limit,
    /// The label count disagrees with the number of lines.
    Count,
    /// A label occurs more than once in the grid.
    Duplicate,
}

/// Validate a whitespace or comma separated explicit label list.
pub fn parse_grid_labels(text: &str, expected: usize) -> Result<Vec<String>, GridLabelError> {
    if text.len() > 16_384 || expected > MAX_GRID_LINES_PER_FAMILY * 2 {
        return Err(GridLabelError::Limit);
    }
    let labels: Vec<String> = text
        .split(|c: char| c.is_ascii_whitespace() || c == ',')
        .filter(|word| !word.is_empty())
        .map(str::to_owned)
        .collect();
    if labels.len() != expected {
        return Err(GridLabelError::Count);
    }
    validate_grid_labels(&labels)?;
    Ok(labels)
}

/// Expand the `numeric` or `alpha` helper to the explicit labels carried by a command.
pub fn generate_grid_labels(
    scheme: &str,
    count: usize,
    start: Option<&str>,
    step: Option<u32>,
    order: GridLabelOrder,
) -> Result<Vec<String>, GridLabelError> {
    if count > MAX_GRID_LINES_PER_FAMILY * 2 {
        return Err(GridLabelError::Limit);
    }
    let mut labels = match scheme {
        "numeric" => {
            let first = start
                .unwrap_or("1")
                .parse::<u32>()
                .map_err(|_| GridLabelError::Invalid)?;
            let step = step.unwrap_or(1);
            if step == 0 {
                return Err(GridLabelError::Invalid);
            }
            (0..count)
                .map(|i| {
                    let offset = u32::try_from(i)
                        .ok()
                        .and_then(|n| n.checked_mul(step))
                        .and_then(|n| first.checked_add(n))
                        .ok_or(GridLabelError::Limit)?;
                    Ok(offset.to_string())
                })
                .collect::<Result<Vec<_>, GridLabelError>>()?
        }
        "alpha" => {
            if step.is_some_and(|value| value != 1) {
                return Err(GridLabelError::Invalid);
            }
            let first = alpha_value(start.unwrap_or("A"))?;
            (0..count)
                .map(|i| {
                    let value = first
                        .checked_add(u32::try_from(i).map_err(|_| GridLabelError::Limit)?)
                        .ok_or(GridLabelError::Limit)?;
                    alpha_label(value)
                })
                .collect::<Result<Vec<_>, GridLabelError>>()?
        }
        _ => return Err(GridLabelError::Invalid),
    };
    if order == GridLabelOrder::Descending {
        labels.reverse();
    }
    validate_grid_labels(&labels)?;
    Ok(labels)
}

/// Apply the contract's exact, case-sensitive label rules and grid-wide uniqueness check.
pub fn validate_grid_labels(labels: &[String]) -> Result<(), GridLabelError> {
    let mut unique = BTreeSet::new();
    for label in labels {
        let chars = label.chars().count();
        if chars == 0 || chars > 16 || label.len() > 64 {
            return Err(GridLabelError::Invalid);
        }
        if !label
            .chars()
            .all(|c| c.is_alphanumeric() || matches!(c, '-' | '_' | '.' | '+' | '/'))
        {
            return Err(GridLabelError::Invalid);
        }
        if !unique.insert(label) {
            return Err(GridLabelError::Duplicate);
        }
    }
    Ok(())
}

fn alpha_value(text: &str) -> Result<u32, GridLabelError> {
    if text.is_empty() || !text.bytes().all(|b| b.is_ascii_uppercase()) {
        return Err(GridLabelError::Invalid);
    }
    text.bytes().try_fold(0u32, |value, byte| {
        value
            .checked_mul(26)
            .and_then(|n| n.checked_add(u32::from(byte - b'A' + 1)))
            .ok_or(GridLabelError::Limit)
    })
}

fn alpha_label(mut value: u32) -> Result<String, GridLabelError> {
    if value == 0 {
        return Err(GridLabelError::Limit);
    }
    let mut reverse = Vec::new();
    while value > 0 {
        value -= 1;
        reverse.push(char::from(
            b'A' + u8::try_from(value % 26).map_err(|_| GridLabelError::Limit)?,
        ));
        value /= 26;
        if reverse.len() > 16 {
            return Err(GridLabelError::Limit);
        }
    }
    reverse.reverse();
    Ok(reverse.into_iter().collect())
}

fn parse_coordinate(text: &str) -> Result<f64, GridExpressionError> {
    let value = text
        .parse::<f64>()
        .map_err(|_| GridExpressionError::Invalid)?;
    if !value.is_finite() {
        return Err(GridExpressionError::NonFinite);
    }
    if value.abs() > GRID_COORDINATE_CAP_MM {
        return Err(GridExpressionError::Limit);
    }
    Ok(if value == 0.0 { 0.0 } else { value })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_grid() -> Grid {
        Grid {
            id: ElementId::parse("01990000-0000-7000-8000-000000000001").unwrap(),
            name: "Main".to_owned(),
            translation_mm: [0.0, 0.0],
            orientation_zw: [0.0, 1.0],
            u: GridFamily::Regular(RegularGridFamily {
                expression: "0".to_owned(),
                labels: vec!["1".to_owned()],
                axis_ids: vec![ElementId::parse("01990000-0000-7000-8000-000000000002").unwrap()],
                span_mm: [-2000.0, 2000.0],
                positions_mm: vec![0.0],
            }),
            v: GridFamily::Drawn(Vec::new()),
        }
    }

    #[test]
    fn stored_records_must_agree_with_their_source_expression() {
        let mut grid = sample_grid();
        assert!(grid.validate().is_ok());
        if let GridFamily::Regular(family) = &mut grid.u {
            family.positions_mm = vec![5.0];
        }
        assert_eq!(
            grid.validate().unwrap_err().code,
            ErrorCode::InvalidArgument
        );
        let mut grid = sample_grid();
        grid.translation_mm[0] = f64::INFINITY;
        assert_eq!(
            grid.validate().unwrap_err().code,
            ErrorCode::NonFiniteNumber
        );
        let mut grid = sample_grid();
        if let GridFamily::Regular(family) = &mut grid.u {
            family.axis_ids.clear();
        }
        assert_eq!(
            grid.validate().unwrap_err().code,
            ErrorCode::InvalidArgument
        );
    }

    #[test]
    fn repeated_axes_and_labels_are_rejected_across_families() {
        let mut grid = sample_grid();
        grid.v = grid.u.clone();
        assert_eq!(grid.validate().unwrap_err().code, ErrorCode::DuplicateId);
        if let GridFamily::Regular(family) = &mut grid.v {
            family.axis_ids =
                vec![ElementId::parse("01990000-0000-7000-8000-000000000003").unwrap()];
        }
        assert_eq!(
            grid.validate().unwrap_err().code,
            ErrorCode::InvalidArgument
        );
    }

    #[test]
    fn expands_and_normalizes_regular_expressions() {
        assert_eq!(
            parse_grid_expression("0, 5*6000").unwrap(),
            (
                "0 5*6000".to_owned(),
                vec![0.0, 6000.0, 12000.0, 18000.0, 24000.0, 30000.0]
            )
        );
        assert_eq!(
            parse_grid_expression("1000 2*4500 6000").unwrap().1,
            vec![1000.0, 5500.0, 10000.0, 16000.0]
        );
        assert_eq!(parse_grid_expression("0").unwrap().1, vec![0.0]);
    }

    #[test]
    fn rejects_bad_spacing_overflow_and_oversized_expressions() {
        for expression in ["", "0 0", "0 -1", "0 201*5", "0 nan", "0 *5"] {
            assert!(parse_grid_expression(expression).is_err(), "{expression:?}");
        }
    }

    #[test]
    fn validates_unicode_labels_and_expands_helpers() {
        assert_eq!(
            parse_grid_labels("А Б Г-1 1/2", 4).unwrap(),
            ["А", "Б", "Г-1", "1/2"]
        );
        assert!(parse_grid_labels("A a", 2).is_ok());
        assert!(parse_grid_labels("A A", 2).is_err());
        assert_eq!(
            generate_grid_labels("alpha", 4, None, None, GridLabelOrder::Ascending).unwrap(),
            ["A", "B", "C", "D"]
        );
        assert_eq!(
            generate_grid_labels("alpha", 3, Some("Y"), None, GridLabelOrder::Ascending).unwrap(),
            ["Y", "Z", "AA"]
        );
        assert_eq!(
            generate_grid_labels("numeric", 3, Some("2"), Some(2), GridLabelOrder::Descending)
                .unwrap(),
            ["6", "4", "2"]
        );
    }
}

/// T01.1 creation request. Every new line identity is supplied explicitly for exact replay.
#[derive(Debug, Clone, PartialEq)]
pub struct CreateGrid {
    /// Complete grid to create.
    pub grid: Grid,
}

impl CreateGrid {
    /// Admit all model arguments before consulting project state.
    pub fn validate_arguments(&self) -> Result<(), CommandError> {
        self.grid.validate()
    }

    /// Versioned, length-prefixed fingerprint of all authored input, including the line identities.
    pub fn content_fingerprint(&self) -> Result<crate::digest::ContentDigest, CommandError> {
        self.validate_arguments()?;
        let mut out = b"BeamCraft/T01/CreateGrid/v1\0".to_vec();
        let put = |out: &mut Vec<u8>, s: &str| {
            out.extend_from_slice(&(s.len() as u64).to_le_bytes());
            out.extend_from_slice(s.as_bytes());
        };
        let num = |out: &mut Vec<u8>, n: f64| -> Result<(), CommandError> {
            out.extend_from_slice(&beamcraft_geom::canonical_f64_bytes(n).map_err(|_| {
                CommandError::new(ErrorCode::NonFiniteNumber, "grid", "non-finite grid value")
            })?);
            Ok(())
        };
        out.extend_from_slice(self.grid.id.as_bytes());
        put(&mut out, &self.grid.name);
        for n in self
            .grid
            .translation_mm
            .into_iter()
            .chain(self.grid.orientation_zw)
        {
            num(&mut out, n)?;
        }
        for family in [&self.grid.u, &self.grid.v] {
            match family {
                GridFamily::Regular(f) => {
                    out.push(0);
                    put(&mut out, &f.expression);
                    for n in f.span_mm {
                        num(&mut out, n)?;
                    }
                    out.extend_from_slice(&(f.axis_ids.len() as u64).to_le_bytes());
                    for ((id, label), position) in
                        f.axis_ids.iter().zip(&f.labels).zip(&f.positions_mm)
                    {
                        out.extend_from_slice(id.as_bytes());
                        put(&mut out, label);
                        num(&mut out, *position)?;
                    }
                }
                GridFamily::Drawn(lines) => {
                    out.push(1);
                    out.extend_from_slice(&(lines.len() as u64).to_le_bytes());
                    for line in lines {
                        out.extend_from_slice(line.axis_id.as_bytes());
                        put(&mut out, &line.label);
                        for n in line.start_mm.into_iter().chain(line.end_mm) {
                            num(&mut out, n)?;
                        }
                    }
                }
            }
        }
        crate::digest::Sha256::digest(&out).map_err(|_| {
            CommandError::new(
                ErrorCode::LimitExceeded,
                "grid",
                "grid request exceeds the encoding cap",
            )
        })
    }
}

/// Independent grid copy. Axis identities are replaced in U then V order.
#[derive(Debug, Clone, PartialEq)]
pub struct CopyGrid {
    /// Existing grid identity.
    pub source_id: ElementId,
    /// Fresh grid identity.
    pub new_id: ElementId,
    /// Optional replacement name; otherwise retain the source name.
    pub name: Option<String>,
    /// World XY offset; a grid copy has no elevation.
    pub offset_mm: [f64; 2],
    /// Fresh identities for every source line in U then V order.
    pub new_axis_ids: Vec<ElementId>,
}
impl CopyGrid {
    /// Validate and fingerprint the copy request independently of the current source state.
    pub fn content_fingerprint(&self) -> Result<crate::digest::ContentDigest, CommandError> {
        let bad = |code, msg| CommandError::new(code, "copy_grid", msg);
        if self.source_id == self.new_id {
            return Err(bad(ErrorCode::DuplicateId, "copy identity is not fresh"));
        }
        if self.new_axis_ids.len() > MAX_GRID_LINES_PER_FAMILY * 2 {
            return Err(bad(
                ErrorCode::LimitExceeded,
                "too many copy axis identities",
            ));
        }
        if self.offset_mm.iter().any(|n| !n.is_finite()) {
            return Err(bad(ErrorCode::NonFiniteNumber, "copy offset is not finite"));
        }
        if self.offset_mm.iter().any(|n| n.abs() > 1e9) {
            return Err(bad(
                ErrorCode::LimitExceeded,
                "copy offset exceeds the coordinate cap",
            ));
        }
        if self
            .name
            .as_ref()
            .is_some_and(|s| !crate::command::label_is_valid(s))
        {
            return Err(bad(ErrorCode::InvalidArgument, "invalid copy name"));
        }
        let mut ids = BTreeSet::from([self.source_id, self.new_id]);
        if self.new_axis_ids.iter().any(|id| !ids.insert(*id)) {
            return Err(bad(
                ErrorCode::DuplicateId,
                "copy axis identity is repeated",
            ));
        }
        let mut bytes = b"BeamCraft/T01/CopyGrid/v1\0".to_vec();
        bytes.extend_from_slice(self.source_id.as_bytes());
        bytes.extend_from_slice(self.new_id.as_bytes());
        match &self.name {
            None => bytes.push(0),
            Some(s) => {
                bytes.push(1);
                bytes.extend_from_slice(&(s.len() as u64).to_le_bytes());
                bytes.extend_from_slice(s.as_bytes());
            }
        }
        for n in self.offset_mm {
            bytes.extend_from_slice(
                &beamcraft_geom::canonical_f64_bytes(n)
                    .map_err(|_| bad(ErrorCode::NonFiniteNumber, "copy offset is not finite"))?,
            );
        }
        bytes.extend_from_slice(&(self.new_axis_ids.len() as u64).to_le_bytes());
        for id in &self.new_axis_ids {
            bytes.extend_from_slice(id.as_bytes());
        }
        crate::digest::Sha256::digest(&bytes).map_err(|_| {
            bad(
                ErrorCode::LimitExceeded,
                "copy request exceeds the encoding cap",
            )
        })
    }
}
